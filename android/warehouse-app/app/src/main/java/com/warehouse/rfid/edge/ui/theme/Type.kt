// See app/src/main/res/values/font_certs.xml for the provider's certificate array —
// standard Android "downloadable fonts" boilerplate. If Inter fails to load at runtime
// (no network / no Google Play Services on the device), text falls back to the system
// sans-serif font automatically; this never affects whether the app builds.
private val googleFontProvider = GoogleFont.Provider(
    providerAuthority = "com.google.android.gms.fonts",
    providerPackage = "com.google.android.gms",
    certificates = R.array.com_google_android_gms_fonts_certs,
)

private fun interFont(weight: FontWeight) = Font(
    googleFont = GoogleFont("Inter"),
    fontProvider = googleFontProvider,
    weight = weight,
)

val InterFontFamily = FontFamily(
    interFont(FontWeight.Normal),
    interFont(FontWeight.Medium),
    interFont(FontWeight.SemiBold),
    interFont(FontWeight.Bold),
)

